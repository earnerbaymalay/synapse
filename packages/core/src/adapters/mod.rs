mod registry_tests {
    use super::*;
    use crate::test_home::HomeGuard;
    use tempfile::tempdir;

    #[test]
    fn all_15_adapters_registered_with_unique_ids() {
        let adapters = all_adapters();
        assert_eq!(adapters.len(), 15);

        let mut ids: Vec<&str> = adapters.iter().map(|a| a.id()).collect();
        let before = ids.len();
        ids.sort();
        ids.dedup();
        assert_eq!(ids.len(), before, "duplicate adapter ids: {:?}", ids);
        assert!(ids.contains(&"kiro"));
        assert!(ids.contains(&"trae"));
    }

    #[test]
    fn next_gen_adapters_registered_with_unique_ids() {
        let next_gen = next_gen_adapters();
        assert_eq!(next_gen.len(), 2);
        let ids: Vec<&str> = next_gen.iter().map(|a| a.id()).collect();
        assert!(ids.contains(&"kiro"));
        assert!(ids.contains(&"trae"));
    }

    #[test]
    fn no_adapter_detects_an_empty_root() {
        let dir = tempdir().unwrap();
        // Several adapters (zed, openai-codex, windsurf) also consult
        // $HOME, where a user-level install counts as present. Pin HOME to
        // an empty temp dir so this asserts the adapters read the scanned
        // root correctly, not whether the machine running the suite happens
        // to have one of these tools installed.
        let home = tempdir().unwrap();
        let _home = HomeGuard::set(home.path());
        for adapter in all_adapters() {
            assert!(
                !adapter.detect(dir.path()),
                "{} falsely detected an empty root",
                adapter.id()
            );
        }
    }
}

#[cfg(test)]
mod mcp_redaction_tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn credentials_in_mcp_args_and_urls_become_placeholders() {
        let mut out = Vec::new();
        parse_and_validate_mcp_server(
            "db",
            &json!({
                "command": "npx",
                "args": ["-y", "@mcp/postgres", "postgresql://admin:s3cretpw@db:5432/app"],
                "env": { "PGSSLMODE": "require" }
            }),
            "cursor",
            &mut out,
        )
        .unwrap();
        parse_and_validate_mcp_server(
            "remote",
            &json!({ "url": "https://mcp.example.com/sse?token=abcd1234efgh5678" }),
            "cursor",
            &mut out,
        )
        .unwrap();

        assert_eq!(
            out[0].command_or_url,
            "npx -y @mcp/postgres postgresql://admin:${SYNAPSE_REDACTED_1}@db:5432/app"
        );
        assert_eq!(out[0].env_placeholders, vec!["PGSSLMODE", "SYNAPSE_REDACTED_1"]);
        assert_eq!(
            out[1].command_or_url,
            "https://mcp.example.com/sse?token=${SYNAPSE_REDACTED_1}"
        );
        for server in &out {
            assert!(!server.command_or_url.contains("s3cretpw"));
            assert!(!server.command_or_url.contains("abcd1234efgh5678"));
        }
    }

    #[test]
    fn clean_mcp_commands_are_unchanged() {
        let mut out = Vec::new();
        parse_and_validate_mcp_server(
            "fs",
            &json!({ "command": "npx", "args": ["-y", "@modelcontextprotocol/server-filesystem", "--token=${GITHUB_TOKEN}"] }),
            "cursor",
            &mut out,
        )
        .unwrap();
        assert_eq!(
            out[0].command_or_url,
            "npx -y @modelcontextprotocol/server-filesystem --token=${GITHUB_TOKEN}"
        );
        assert!(out[0].env_placeholders.is_empty());
    }
}

